# Paths a writer reviews before the first deliberate commit. Build output,
# drafts, and raw media are not in this list.
TRACKED_PATHS = (
    "manifest.json",
    "rules.json",
    ".gitignore",
    "corpus",
    "transcripts",
    "gold",
    "sessions",
    "holdouts",
)

# Optional writer-authored editorial prose, folded into the guide by build.
# They are tracked like the corpus and never measured. `load_notes` reads
# them; `save_note` appends a dated rule.
NOTE_FILES = (
    ("style", "STYLE.md"),
    ("audience", "AUDIENCE.md"),
)

Origin = Literal["ai-first", "writer-first"]
# Provenance answers "where did the first draft come from?". It is recorded,
# never measured. Corpus files default to `unaided`; a learned pair carries
# whatever its meta.json says.
ProvenanceOrigin = Literal["unaided", "writer-first", "ai-first"]
# Confirmation is the writer's claim about the final. `origin` means the
# provenance itself settles it (an unaided or writer-first draft is theirs).
# `promoted` means they deliberately lifted an AI-first final into gold.
Confirmation = Literal["none", "origin", "promoted"]


@dataclass(frozen=True)
class Provenance:
    origin: ProvenanceOrigin | None
    confirmation: Confirmation = "none"
    model: str | None = None
    tool: str | None = None


def parse_origin(value: str, *, path: str) -> Origin:
    match value:
        case "ai-first" | "writer-first":
            return value
        case _:
            raise ProjectError(
                f"{path}: origin must be 'ai-first' or 'writer-first', got {value!r}"
            )


def parse_provenance_origin(value: str, *, path: str) -> ProvenanceOrigin:
    match value:
        case "unaided" | "ai-first" | "writer-first":
            return value
        case _:
            raise ProjectError(
                f"{path}: provenance.origin must be 'unaided', 'writer-first', or "
                f"'ai-first', got {value!r}"
            )


def parse_confirmation(value: str, *, path: str) -> Confirmation:
    match value:
        case "none" | "origin" | "promoted":
            return value
        case _:
            raise ProjectError(
                f"{path}: provenance.confirmation must be 'none', 'origin', or "
                f"'promoted', got {value!r}"
            )


def read_provenance(meta: dict[str, object], *, path: str) -> Provenance:
    """Read provenance from a learn `meta.json`, with v0.1 defaults.

    v0.1 wrote only a top-level `origin`. A missing `origin` is left unknown:
    the pair is measured as edited rather than granted gold, and build warns
    about it. A v0.1 `writer-first` pair keeps gold, because the writer wrote
    the first draft.
    """
    raw = meta.get("provenance")
    if raw is not None and not isinstance(raw, dict):
        raise ProjectError(f"{path}: provenance must be an object.")
    nested = raw if isinstance(raw, dict) else {}
    origin_value = nested.get("origin", meta.get("origin"))
    if origin_value is None:
        origin: ProvenanceOrigin | None = None
    elif isinstance(origin_value, str):
        origin = parse_provenance_origin(origin_value, path=path)
    else:
        raise ProjectError(f"{path}: provenance.origin must be a string.")
    confirmation_value = nested.get("confirmation")
    if confirmation_value is None:
        confirmation: Confirmation = "origin" if origin == "writer-first" else "none"
    elif isinstance(confirmation_value, str):
        confirmation = parse_confirmation(confirmation_value, path=path)
    else:
        raise ProjectError(f"{path}: provenance.confirmation must be a string.")
    return Provenance(
        origin=origin,
        confirmation=confirmation,
        model=_optional_text(nested.get("model")),
        tool=_optional_text(nested.get("tool")),
    )


def placement_for(provenance: Provenance) -> Tier:
    """Which measured tier a learned final belongs in.

    Gold is reserved for writing the writer stands behind. A writer-first draft
    qualifies through its origin; an AI-first final qualifies only after an
    explicit promotion. Unaided writing reaches gold through `corpus/gold`
    and never passes through this function.
    """
    if provenance.confirmation == "promoted":
        return "gold"
    if provenance.origin == "writer-first" and provenance.confirmation == "origin":
        return "gold"
    return "edited"


def provenance_json(
    origin: str | None,
    *,
    confirmation: str,
    model: str | None = None,
    tool: str | None = None,
) -> dict[str, object]:
    return {
        "origin": origin,
        "confirmation": confirmation,
        "model": _optional_text(model),
        "tool": _optional_text(tool),
    }


def _optional_text(value: object) -> str | None:
    if isinstance(value, str):
        text = value.strip()
        if text:
            return text
    return None


def _never(value: Never) -> Never:
    raise RuntimeError(f"unhandled variant: {value!r}")


def default_manifest() -> dict[str, object]:
    return {
        "kind": "ghostless",
        "version": 1,
        "weights": {
            "gold": DEFAULT_WEIGHTS["gold"],
            "silver": DEFAULT_WEIGHTS["silver"],
            "bronze": DEFAULT_WEIGHTS["bronze"],
            "edited": DEFAULT_WEIGHTS["edited"],
        },
        "goldVoiceMinimum": 10,
        "updateCheck": True,
        "failUnder": 70,
    }


def load_manifest(root: Path) -> dict[str, object]:
    path = root / "manifest.json"
    if not path.is_file():
        raise ProjectError(f"Missing manifest.json in {root}. Run `ghostless init`.")
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ProjectError(f"{path}: {exc}") from exc
    if not isinstance(raw, dict) or raw.get("kind") != "ghostless":
        raise ProjectError(f"{path} is not a ghostless manifest (kind must be \"ghostless\").")
    weights = dict(DEFAULT_WEIGHTS)
    custom = raw.get("weights") or {}
    if not isinstance(custom, dict):
        raise ProjectError(f"{path}: weights must be an object.")
    for key in ("gold", "silver", "bronze", "edited"):
        if key not in custom:
            continue
        try:
            number = float(custom[key])
        except (TypeError, ValueError) as exc:
            raise ProjectError(f"{path}: weights.{key} must be a number.") from exc
        if number <= 0:
            raise ProjectError(f"{path}: weights.{key} must be positive.")
        match key:
            case "gold" | "silver" | "bronze" | "edited":
                weights[key] = number
            case _ as unexpected:
                _never(unexpected)
    minimum = _positive_int(raw.get("goldVoiceMinimum", 10), path=path, field="goldVoiceMinimum")
    fail_under = raw.get("failUnder", 70)
    try:
        fail_under_int = int(fail_under)
    except (TypeError, ValueError) as exc:
        raise ProjectError(f"{path}: failUnder must be an integer.") from exc
    if not 0 <= fail_under_int <= 100:
        raise ProjectError(f"{path}: failUnder must be between 0 and 100.")
    update_check = raw.get("updateCheck", True)
    if not isinstance(update_check, bool):
        raise ProjectError(f"{path}: updateCheck must be true or false.")
    pieces = raw.get("pieces") or []
    if not isinstance(pieces, list):
        raise ProjectError(f"{path}: pieces must be a list.")
    return {
        "root": root,
        "weights": weights,
        "goldVoiceMinimum": minimum,
        "failUnder": fail_under_int,
        "updateCheck": update_check,
        "pieces": pieces,
    }


def load_notes(root: Path) -> dict[str, str | None]:
    """Optional writer-authored editorial prose, folded into the guide.

    `STYLE.md` governs what a piece must do, contain, and prove (argument,
    evidence, structure, readiness). `AUDIENCE.md` governs who reads it.
    Both are tracked sources like the corpus; the generated guide is ignored.
    Absence never blocks a build, and neither file is ever measured.
    """
    notes: dict[str, str | None] = {}
    for key, name in NOTE_FILES:
        path = root / name
        if not path.is_file():
            notes[key] = None
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeError as exc:
            raise ProjectError(f"{path} is not valid UTF-8.") from exc
        notes[key] = text.strip() or None
    return notes


def save_note(root: Path, *, kind: str, text: str) -> dict[str, object]:
    """Append one confirmed editorial rule to STYLE.md or AUDIENCE.md.

    `kind` is ``"style"`` or ``"audience"``. The line is dated, so a rule the
    writer confirms later gets its own entry. Saving the same rule on the same
    day is a no-op rather than a duplicate.
    """
    name = {"style": "STYLE.md", "audience": "AUDIENCE.md"}.get(kind)
    if name is None:
        raise ProjectError("save needs --style or --audience.")
    rule = " ".join(text.split())
    if not rule:
        raise ProjectError("The rule text must not be empty.")
    path = root / name
    line = f"- {datetime.now(timezone.utc).strftime('%Y-%m-%d')} {rule}"
    heading = f"# {kind.title()}\n"
    if not path.is_file():
        path.write_text(heading + "\n" + line + "\n", encoding="utf-8")
        return {"path": path, "created": True, "appended": True}
    existing = path.read_text(encoding="utf-8")
    if line in existing.splitlines():
        return {"path": path, "created": False, "appended": False}
    if not existing.strip():
        path.write_text(heading + "\n" + line + "\n", encoding="utf-8")
        return {"path": path, "created": True, "appended": True}
    body = existing.rstrip("\n") + "\n\n" + line + "\n"
    path.write_text(body, encoding="utf-8")
    return {"path": path, "created": False, "appended": True}


def _positive_int(value: object, *, path: Path, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, float, str)):
        raise ProjectError(f"{path}: {field} must be an integer.")
    try:
        number = int(value)
    except ValueError as exc:
        raise ProjectError(f"{path}: {field} must be an integer.") from exc
    if number < 1:
        raise ProjectError(f"{path}: {field} must be at least 1.")
    return number


def init_project(directory: Path, *, force: bool = False, git: bool = True) -> Path:
    """Create the voice-data layout, manifest, ignore rules, and local Git history.

    Git is local only: no remote is added, and nothing is staged or committed.
    """
    directory.mkdir(parents=True, exist_ok=True)
    manifest_path = directory / "manifest.json"
    if manifest_path.exists() and not force:
        raise ProjectError(
            f"{manifest_path} already exists. Pass --force to rewrite the manifest defaults."
        )
    gitignore_path = directory / ".gitignore"
    if gitignore_path.exists() and LEGACY_GITIGNORE_MARKER in gitignore_path.read_text(
        encoding="utf-8"
    ):
        raise ProjectError(
            f"{gitignore_path} still has the v0.1 ignore block, which keeps your writing "
            f"out of Git. Run `ghostless migrate --project {directory}` to review the change "
            "before anything is committed."
        )
    ensure_layout(directory)
    manifest_path.write_text(
        json.dumps(default_manifest(), indent=2) + "\n",
        encoding="utf-8",
    )
    _ensure_gitignore(gitignore_path)
    if git:
        ensure_local_git(directory)
    return directory


def ensure_layout(directory: Path) -> list[str]:
    """Create the data-repo directories. Returns the ones that did not exist."""
    directory.mkdir(parents=True, exist_ok=True)
    created: list[str] = []
    for relative in DATA_DIRS:
        folder = directory / relative
        if not folder.is_dir():
            created.append(relative)
        folder.mkdir(parents=True, exist_ok=True)
        keep = folder / ".gitkeep"
        if not keep.exists():
            keep.write_text("", encoding="utf-8")
    return created


def _ensure_gitignore(path: Path) -> None:
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    if GITIGNORE_MARKER in existing:
        return
    prefix = existing
    if prefix and not prefix.endswith("\n"):
        prefix += "\n"
    if prefix and not prefix.endswith("\n\n"):
        prefix += "\n"
    path.write_text(prefix + GITIGNORE_BLOCK, encoding="utf-8")


def migrate_project(directory: Path) -> dict[str, object]:
    """Move a v0.1 voice directory to the data-repo layout.

    Changes only `.gitignore` and missing directories. It never stages,
    commits, pushes, or adds a remote, so material the writer kept out of Git
    stays out until they add it on purpose.
    """
    directory = directory.resolve()
    load_manifest(directory)
    gitignore_path = directory / ".gitignore"
    existing = gitignore_path.read_text(encoding="utf-8") if gitignore_path.exists() else ""
    legacy_removed = LEGACY_GITIGNORE_MARKER in existing
    if legacy_removed and LEGACY_GITIGNORE_BLOCK not in existing:
        raise ProjectError(
            f"{gitignore_path} has the v0.1 ghostless ignore block, but it was edited. "
            "Remove the lines under "
            f"'{LEGACY_GITIGNORE_MARKER}' by hand (they ignore corpus/, transcripts/, "
            "and gold/), then run `ghostless migrate` again."
        )
    updated = _data_repo_gitignore(existing, drop_legacy=legacy_removed)
    changed = updated != existing
    if changed:
        gitignore_path.write_text(updated, encoding="utf-8")
    created = ensure_layout(directory)
    return {
        "root": directory,
        "gitignore": gitignore_path,
        "changed": changed,
        "legacy_removed": legacy_removed,
        "created": created,
        "tracked": TRACKED_PATHS,
    }


def _data_repo_gitignore(existing: str, *, drop_legacy: bool) -> str:
    text = existing
    if drop_legacy:
        text = text.replace(LEGACY_GITIGNORE_BLOCK, "", 1)
    if GITIGNORE_MARKER in text:
        if not drop_legacy:
            return existing
        # A writer who pasted the new block in by hand keeps exactly one copy.
        return _clean_gitignore(text) + "\n"
    body = _clean_gitignore(text) if drop_legacy else text.rstrip("\n")
    if not body:
        return GITIGNORE_BLOCK
    return body + "\n\n" + GITIGNORE_BLOCK


def _clean_gitignore(text: str) -> str:
    return re.sub(r"\n{3,}", "\n\n", text.strip("\n"))


def git_toplevel(directory: Path) -> Path | None:
    """The work-tree root that contains this directory, if any."""
    result = _git(["rev-parse", "--show-toplevel"], directory)
    if result is None or result.returncode != 0:
        return None
    value = result.stdout.strip()
    return Path(value) if value else None


def ensure_local_git(directory: Path) -> str:
    """Create local Git history when the directory is not already in a repo.

    Returns "created", "existing", "parent:<path>", or "unavailable". A
    directory inside a larger repository is left alone rather than turned into
    a nested repository.
    """
    top = git_toplevel(directory)
    if top is not None:
        if top == directory.resolve():
            return "existing"
        return f"parent:{top}"
    result = _git(["init", "--quiet"], directory)
    if result is None:
        return "unavailable"
    if result.returncode != 0:
        raise ProjectError(f"git init failed in {directory}: {result.stderr.strip()}")
    return "created"


def _git(arguments: list[str], cwd: Path) -> subprocess.CompletedProcess[str] | None:
    try:
        return subprocess.run(
            ["git", *arguments],
            cwd=str(cwd),
            check=False,
            capture_output=True,
            text=True,
        )
    except OSError:
        return None


def slug_for(date_text: str, section: str | None) -> str:
    """`YYYY-MM-DD` plus a section slug, matching learn and session ids."""
    slug = date_text
    if section:
        extra = SLUG_RE.sub("-", section.casefold()).strip("-")
        if extra:
            slug = f"{date_text}-{extra}"
    return slug


def fresh_directory(parent: Path, slug: str) -> Path:
    """A sibling that does not exist yet, suffixed -2, -3, ... when needed."""
    candidate = parent / slug
    if not candidate.exists():
        return candidate
    number = 2
    while (parent / f"{slug}-{number}").exists():
        number += 1
    return parent / f"{slug}-{number}"


def new_session_id(root: Path, *, date: str, section: str | None = None) -> str:
    """Return an unused edit-session id: `YYYY-MM-DD[-section][-N]`.

    Sessions live in `sessions/<id>/` with `session.json`, `before.md`, and
    `after.md`. Callers create the directory; the id is not reserved until then.
    """
    if not DATE_RE.fullmatch(date):
        raise ProjectError("Session date must be YYYY-MM-DD.")
    return fresh_directory(root / "sessions", slug_for(date, section)).name


def discover(root: Path, manifest: dict[str, object]) -> list[Piece]:
    weights = manifest["weights"]
    if not isinstance(weights, dict):
        raise ProjectError("manifest weights are missing.")
    pieces: list[Piece] = []
    specs: list[tuple[Path, Tier, Kind]] = [
        (root / "corpus" / "gold", "gold", "prose"),
        (root / "corpus" / "silver", "silver", "prose"),
        (root / "corpus" / "bronze", "bronze", "prose"),
        (root / "corpus" / "spoken", "silver", "spoken"),
        (root / "transcripts", "silver", "spoken"),
    ]
    for folder, tier, kind in specs:
        for path in _iter_texts(folder):
            pieces.append(
                _piece_from_file(
                    root,
                    path,
                    default_tier=tier,
                    default_kind=kind,
                    weights=weights,
                    origin="unaided",
                    confirmation="origin",
                )
            )
    pieces.extend(_learned_pieces(root, weights))
    pieces = _apply_overrides(root, pieces, manifest.get("pieces") or [], weights)
    pieces = [piece for piece in pieces if piece.text.strip()]
    pieces.sort(key=lambda piece: (piece.tier, piece.kind, piece.path))
    return pieces


def _iter_texts(folder: Path) -> list[Path]:
    if not folder.is_dir():
        return []
    found: list[Path] = []
    for path in folder.rglob("*"):
        if not path.is_file():
            continue
        if path.name.startswith(".") or path.name.lower() in SKIP_NAMES:
            continue
        if path.suffix.lower() not in TEXT_SUFFIXES:
            continue
        found.append(path)
    return sorted(found)


def _piece_from_file(
    root: Path,
    path: Path,
    *,
    default_tier: Tier,
    default_kind: Kind,
    weights: dict[str, float],
    learned: bool = False,
    origin: str | None = None,
    confirmation: str | None = None,
    model: str | None = None,
    tool: str | None = None,
    section_hint: str | None = None,
) -> Piece:
    try:
        raw = path.read_text(encoding="utf-8")
    except UnicodeError as exc:
        raise ProjectError(f"{path} is not valid UTF-8.") from exc
    meta, body = split_frontmatter(raw)
    tier = _override_tier(meta.get("tier"), default_tier, path=str(path))
    kind = _override_kind(meta.get("kind"), default_kind, path=str(path))
    section = meta.get("section") or section_hint or _section_from_path(path, root, tier, kind)
    if section == "":
        section = None
    return Piece(
        path=_rel(root, path),
        tier=tier,
        kind=kind,
        section=section,
        weight=float(weights[tier]),
        text=body.strip(),
        origin=origin,
        learned=learned,
        confirmation=confirmation,
        model=model,
        tool=tool,
    )


def _section_from_path(path: Path, root: Path, tier: Tier, kind: Kind) -> str | None:
    if kind == "spoken":
        base = root / "corpus" / "spoken"
        alt = root / "transcripts"
    else:
        base = root / "corpus" / tier
        alt = base
    for folder in (base, alt):
        try:
            relative = path.relative_to(folder)
        except ValueError:
            continue
        if len(relative.parts) > 1:
            return relative.parts[0]
        return None
    return None


def _learned_pieces(root: Path, weights: dict[str, float]) -> list[Piece]:
    folder = root / "gold"
    if not folder.is_dir():
        return []
    pieces: list[Piece] = []
    for meta_path in sorted(folder.glob("*/meta.json")):
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ProjectError(f"{meta_path}: {exc}") from exc
        if not isinstance(meta, dict):
            raise ProjectError(f"{meta_path} must be an object.")
        after = meta_path.parent / str(meta.get("afterFile") or "after.md")
        if not after.is_file():
            raise ProjectError(f"{meta_path} points at a missing after file.")
        provenance = read_provenance(meta, path=str(meta_path))
        section = meta.get("section")
        section_hint = section if isinstance(section, str) and section else None
        kind_raw = meta.get("kind")
        default_kind: Kind = "prose"
        if isinstance(kind_raw, str) and kind_raw:
            default_kind = _override_kind(kind_raw, "prose", path=str(meta_path))
        piece = _piece_from_file(
            root,
            after,
            default_tier=placement_for(provenance),
            default_kind=default_kind,
            weights=weights,
            learned=True,
            origin=provenance.origin,
            confirmation=provenance.confirmation,
            model=provenance.model,
            tool=provenance.tool,
            section_hint=section_hint,
        )
        pieces.append(piece)
    return pieces


def _apply_overrides(
    root: Path,
    pieces: list[Piece],
    entries: object,
    weights: dict[str, float],
) -> list[Piece]:
    if not isinstance(entries, list) or not entries:
        return pieces
    by_path = {piece.path: piece for piece in pieces}
    for entry in entries:
        if not isinstance(entry, dict) or "path" not in entry:
            raise ProjectError("manifest pieces entries need a path.")
        rel = str(entry["path"])
        path = root / rel
        if not path.is_file():
            raise ProjectError(f"manifest piece not found: {rel}")
        existing = by_path.get(rel.replace("\\", "/"))
        default_tier: Tier = existing.tier if existing else "silver"
        default_kind: Kind = existing.kind if existing else "prose"
        tier = _override_tier(
            str(entry["tier"]) if entry.get("tier") else None,
            default_tier,
            path=rel,
        )
        kind = _override_kind(
            str(entry["kind"]) if entry.get("kind") else None,
            default_kind,
            path=rel,
        )
        section_value = entry.get("section", existing.section if existing else None)
        section = str(section_value) if isinstance(section_value, str) and section_value else None
        try:
            raw = path.read_text(encoding="utf-8")
        except UnicodeError as exc:
            raise ProjectError(f"{path} is not valid UTF-8.") from exc
        _, body = split_frontmatter(raw)
        by_path[rel.replace("\\", "/")] = Piece(
            path=rel.replace("\\", "/"),
            tier=tier,
            kind=kind,
            section=section,
            weight=float(weights[tier]),
            text=body.strip(),
            origin=existing.origin if existing else None,
            learned=existing.learned if existing else False,
            confirmation=existing.confirmation if existing else None,
            model=existing.model if existing else None,
            tool=existing.tool if existing else None,
        )
    return list(by_path.values())


def _override_tier(value: str | None, default: Tier, *, path: str) -> Tier:
    if not value:
        return default
    match value:
        case "gold" | "silver" | "bronze" | "edited":
            return value
        case _:
            raise ProjectError(f"{path}: unknown tier {value!r}")


def _override_kind(value: str | None, default: Kind, *, path: str) -> Kind:
    if not value:
        return default
    match value:
        case "prose" | "spoken":
            return value
        case _:
            raise ProjectError(f"{path}: unknown kind {value!r}")


def _rel(root: Path, path: Path) -> str:
    return path.resolve().relative_to(root.resolve()).as_posix()
